/// The entrypoint for the **server** environment, which for a static build is
/// the only one that renders anything: `jaspr build` runs this once and writes
/// one HTML file per route -- `build/jaspr/index.html`,
/// `build/jaspr/models/index.html`, `build/jaspr/models/embeddings/index.html`,
/// `build/jaspr/changelog/index.html` and
/// `build/jaspr/measurements/index.html` -- and two text files,
/// `build/jaspr/llms.txt` and `build/jaspr/llms-full.txt` (`lib/llms_txt.dart`).
library;

import 'package:jaspr/server.dart';
import 'package:jaspr_router/jaspr_router.dart';

import 'changelog/changelog_page.dart';
import 'landing/landing_page.dart';
import 'llms_txt.dart';
import 'measurements/measurements_page.dart';
import 'models/models_page.dart';
import 'project.dart';
import 'seo.dart';

// Generated by jaspr_builder — do not edit.
import 'main.server.options.dart';

/// The two halves of `/models`. One builder, so the halves cannot drift apart
/// in anything but what [ModelsTab] says differs.
Route _modelsRoute(ModelsTab tab, String title, String description) => Route(
  path: tab.path,
  builder: (context, state) => Document(
    title: title,
    lang: 'en',
    meta: {'description': description},
    head: [
      ...fontLinks(),
      ...seoHead(
        title: title,
        description: description,
        applicationDescription: kLandingDescription,
        version: packageVersion,
        path: tab.path,
      ),
    ],
    body: ModelsPage(version: packageVersion, tab: tab),
  ),
);

void main() {
  // `txt` beside jaspr's default suffixes, or the server answers 404 to
  // `/llms.txt` before any route sees it (jaspr 0.23.4
  // `server_handler.dart:81-92`).
  Jaspr.initializeApp(
    options: defaultServerOptions,
    allowedPathSuffixes: const ['html', 'htm', 'xml', 'txt'],
  );

  // `jaspr_router` in static mode renders every route it is given, which is
  // how the build knows `/changelog` exists: nothing links the two pages at
  // build time, and a route missing here is a page missing from the deploy.
  runApp(
    Router(
      routes: [
        Route(
          path: '/',
          builder: (context, state) => Document(
            title: kLandingTitle,
            lang: 'en',
            meta: const {'description': kLandingDescription},
            head: [
              ...fontLinks(),
              ...seoHead(
                title: kLandingTitle,
                description: kLandingDescription,
                version: packageVersion,
              ),
            ],
            body: LandingPage(version: packageVersion),
          ),
        ),
        _modelsRoute(ModelsTab.llm, kModelsTitle, kModelsDescription),
        _modelsRoute(
          ModelsTab.embeddings,
          kEmbeddingsTitle,
          kEmbeddingsDescription,
        ),
        Route(
          path: '/changelog',
          builder: (context, state) => Document(
            title: kChangelogTitle,
            lang: 'en',
            meta: const {'description': kChangelogDescription},
            head: [
              ...fontLinks(),
              ...seoHead(
                title: kChangelogTitle,
                description: kChangelogDescription,
                applicationDescription: kLandingDescription,
                version: packageVersion,
                path: '/changelog',
              ),
            ],
            body: ChangelogPage(
              version: packageVersion,
              markdown: changelogMarkdown,
            ),
          ),
        ),
        Route(
          path: '/measurements',
          builder: (context, state) => Document(
            title: kMeasurementsTitle,
            lang: 'en',
            meta: const {'description': kMeasurementsDescription},
            head: [
              ...fontLinks(),
              ...seoHead(
                title: kMeasurementsTitle,
                description: kMeasurementsDescription,
                applicationDescription: kLandingDescription,
                version: packageVersion,
                path: '/measurements',
              ),
            ],
            body: MeasurementsPage(
              version: packageVersion,
              markdown: measurementsMarkdown,
            ),
          ),
        ),
        Route(
          path: kLlmsTxtPath,
          builder: (context, state) =>
              TextFile(llmsTxt(version: packageVersion)),
        ),
        Route(
          path: kLlmsFullTxtPath,
          builder: (context, state) => TextFile(
            llmsFullTxt(
              readme: readmeMarkdown,
              measurements: measurementsMarkdown,
            ),
          ),
        ),
      ],
    ),
  );
}
